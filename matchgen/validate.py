"""Validation report: synthetic league vs the reference parameters.

Runs N independent seasons (seeds never used in calibration), plus the published
season, and writes VALIDATION.md and a chart.

Usage:  python -m matchgen.validate --seasons 20 --published data
"""

import argparse
import json
import math
import os
from multiprocessing import Pool

import pandas as pd

from . import config as C
from .metrics import league_metrics, dispersion_by_xg, model_scoreline_probs
from .season import run_season

VAL_SEEDS = list(range(101, 200))

# Approximate per-match texture of a modern top-flight league (both teams combined), from widely published
# season aggregates. These are sanity ranges, not fitted targets.
TEXTURE_RANGES = {
    "shots": (23, 28), "xg_per_shot": (0.105, 0.125), "shots_on_target": (8, 10), "corners": (9.5, 11.5),
    "fouls": (19, 23), "yellow_cards": (3.3, 4.6), "red_cards": (0.08, 0.20), "penalties_awarded": (0.22, 0.35),
    "offsides": (3.0, 4.5), "passes": (850, 1100), "pass_accuracy_pct": (78, 85), "ball_in_play_min": (53, 59),
}


def _season(args):
    seed, = args
    s = run_season(seed, keep_events=True)
    ev = s["events"]
    shots = [e for e in ev if e["type"] == "shot"]
    passes = [e for e in ev if e["type"] == "pass"]
    n = len(s["matches"])
    tex = {
        "shots": len(shots) / n,
        "xg_per_shot": sum(e["xg"] for e in shots) / len(shots),
        "shots_on_target": sum(e["outcome"] in ("goal", "saved") for e in shots) / n,
        "corners": sum(1 for e in passes if e["set_piece"] == "corner") / n,
        "fouls": sum(e["type"] == "foul" for e in ev) / n,
        "yellow_cards": sum(e["card"] == "yellow" for e in ev) / n,
        "red_cards": sum(e["card"] in ("red", "second_yellow") for e in ev) / n,
        "penalties_awarded": sum(e["type"] == "penalty_awarded" for e in ev) / n,
        "offsides": sum(e["type"] == "offside" for e in ev) / n,
        "passes": len(passes) / n,
        "pass_accuracy_pct": 100 * sum(e["outcome"] == "complete" for e in passes) / len(passes),
        "ball_in_play_min": sum(m["ball_in_play_s"] for m in s["matches"]) / n / 60,
    }
    return s["matches"], tex


def _se(p, n):
    return math.sqrt(max(p * (1 - p), 1e-9) / n)


def run(n_seasons, published_dir, out_md, chart_path, procs=2):
    with Pool(procs) as pool:
        res = pool.map(_season, [(sd,) for sd in VAL_SEEDS[:n_seasons]])
    matches = [m for r in res for m in r[0]]
    tex = {k: sum(r[1][k] for r in res) / len(res) for k in res[0][1]}
    mets = league_metrics(matches)
    pub = league_metrics(pd.read_csv(os.path.join(published_dir, "matches.csv")).to_dict("records")) if published_dir else None
    disp = dispersion_by_xg(matches)
    sc_sim = pd.Series([f"{m['home_goals']}-{m['away_goals']}" for m in matches]).value_counts(normalize=True)
    sc_ref = model_scoreline_probs(matches[:4000])

    # ---------------------------------------------------------------- report
    n = len(matches)
    lines = []
    lines.append("# Validation report\n")
    lines.append(f"Generated by `python -m matchgen.validate --seasons {n_seasons}`. "
                 f"{n_seasons} independent seasons ({n:,} matches), simulated with seeds that were **never used in calibration**.\n")
    lines.append("Reference values are league-level parameters fitted on historical top-flight xG data (2014-2025). "
                 "Only three engine knobs are fitted (chance rate, home factor, strength spread); they target total xG, "
                 "the home/away xG split and the draw rate. **Everything else below is an out-of-fit check.**\n")
    lines.append("## 1. League rates\n")
    lines.append("| Metric | Reference | Synthetic (all seasons) | ± 2 SE | Published season | Fitted? |")
    lines.append("|---|---|---|---|---|---|")
    labels = [("home_xg", "Home xG / match", True), ("away_xg", "Away xG / match", True),
              ("goals_per_game", "Goals / match", False), ("home_win", "Home win", False), ("draw", "Draw", True),
              ("away_win", "Away win", False), ("btts", "Both teams score", False), ("over_2_5", "Over 2.5 goals", False)]
    for k, lab, fitted in labels:
        t = C.TARGETS[k]
        v = mets[k]
        if k in ("home_win", "draw", "away_win", "btts", "over_2_5"):
            se2 = 2 * _se(v, n)
            fmt = lambda z: f"{100 * z:.1f}%"
            band = f"±{100 * se2:.1f} pp"
        else:
            fmt = lambda z: f"{z:.3f}"
            band = "—"
        pv = fmt(pub[k]) if pub else "—"
        lines.append(f"| {lab} | {fmt(t)} | **{fmt(v)}** | {band} | {pv} | {'yes' if fitted else 'no'} |")
    lines.append(f"\nGoals per unit of xG: synthetic {mets['goals_per_xg']:.4f} vs reference {C.XG_TO_GOAL_SCALE:.4f}.\n")
    lines.append("A single 380-match season carries sampling noise of roughly ±2-3 percentage points on each result "
                 "rate, so the published season is expected to wander around the reference.\n")

    lines.append("## 2. Goal-count dispersion (not fitted)\n")
    lines.append("Real goals are **under-dispersed** relative to Poisson: for a given xG, goals vary less than a Poisson "
                 "model assumes. The reference model captures this as Binomial(n = 2·xG + 1). The generator was not "
                 "told this; each shot is a Bernoulli trial, so dispersion emerges from the shot mix.\n")
    lines.append("| Team xG bin | Team-matches | Mean xG | Mean goals | Synthetic var/mean | Reference var/mean | Poisson |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in disp:
        lines.append(f"| {r['xg_bin']} | {r['team_matches']:,} | {r['mean_xg']:.2f} | {r['mean_goals']:.2f} | "
                     f"**{r['var_over_mean']:.3f}** | {r['reference_var_over_mean']:.3f} | 1.000 |")
    lines.append("")

    lines.append("## 3. Scorelines (not fitted)\n")
    lines.append("Synthetic scoreline frequencies vs the reference model (Binomial margins + Dixon-Coles ρ = -0.06) "
                 "evaluated on the same matches' xG.\n")
    lines.append("| Score | Synthetic | Reference model |")
    lines.append("|---|---|---|")
    for s in list(sc_sim.index[:12]):
        lines.append(f"| {s} | {100 * sc_sim[s]:.1f}% | {100 * sc_ref.get(s, 0):.1f}% |")
    lines.append("")

    lines.append("## 4. Match texture (sanity ranges, not fitted)\n")
    lines.append("Per match, both teams combined. Ranges are approximate figures for a modern top flight.\n")
    lines.append("| Measure | Synthetic | Typical range | In range |")
    lines.append("|---|---|---|---|")
    for k, (lo, hi) in TEXTURE_RANGES.items():
        v = tex[k]
        ok = lo <= v <= hi
        lines.append(f"| {k.replace('_', ' ')} | {v:.3f} | {lo}–{hi} | {'yes' if ok else '**no**'} |")
    lines.append("")
    lines.append("## 5. Known limits\n")
    lines.append("- Both-teams-to-score runs about 1.5-2 pp above the reference across many seasons (just outside the 2 SE band); "
                 "the score-effect strength that keeps BTTS down also drives goal dispersion, and the two were balanced.")
    lines.append("- Goals are under-dispersed as in reality, but less so than the reference at low team xG (below ~1.0): "
                 "the synthetic shot mix produces slightly more 2-goal games from few chances.")
    lines.append("- Player-level distributions (e.g. how goals spread across a squad) are plausible but not calibrated.")
    lines.append("- Locations are realistic in aggregate; individual passes are not tracking-accurate.")
    lines.append("- Club ratings are fixed for the season (no form swings, injuries or managerial changes).")
    lines.append("- Reference rates come from one league's recent era; home advantage in particular drifts by era.\n")

    with open(out_md, "w") as f:
        f.write("\n".join(lines))
    with open(out_md.replace(".md", ".json"), "w") as f:
        json.dump({"league": mets, "published": pub, "texture": tex, "dispersion": disp,
                   "scorelines_sim": sc_sim.head(15).to_dict(), "scorelines_ref": sc_ref}, f, indent=2, default=float)

    if chart_path:
        _chart(mets, disp, sc_sim, sc_ref, chart_path)
    return mets, tex, disp


def _chart(mets, disp, sc_sim, sc_ref, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ink, muted, grid = "#1f2328", "#59636e", "#d8dee4"
    c_sim, c_ref = "#2f6fdf", "#d9822b"
    plt.rcParams.update({"font.size": 10, "axes.edgecolor": grid, "axes.labelcolor": ink, "xtick.color": muted,
                         "ytick.color": muted, "axes.spines.top": False, "axes.spines.right": False})
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))

    ax = axes[0]
    keys = ["home_win", "draw", "away_win", "btts", "over_2_5"]
    labs = ["Home win", "Draw", "Away win", "BTTS", "Over 2.5"]
    xs = range(len(keys))
    ax.bar([i - 0.2 for i in xs], [100 * C.TARGETS[k] for k in keys], 0.38, color=c_ref, label="Reference")
    ax.bar([i + 0.2 for i in xs], [100 * mets[k] for k in keys], 0.38, color=c_sim, label="Synthetic")
    ax.set_xticks(list(xs), labs)
    ax.set_ylabel("% of matches")
    ax.set_title("Result and goal markets", loc="left", color=ink, fontsize=11)
    ax.grid(axis="y", color=grid, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.legend(frameon=False)

    ax = axes[1]
    mx = [r["mean_xg"] for r in disp]
    ax.plot(mx, [r["var_over_mean"] for r in disp], "o-", color=c_sim, label="Synthetic")
    ax.plot(mx, [r["reference_var_over_mean"] for r in disp], "s--", color=c_ref, label="Reference Binomial(2xG+1)")
    ax.axhline(1.0, color=muted, linewidth=1, linestyle=":")
    ax.text(mx[-1], 1.01, "Poisson", color=muted, ha="right", va="bottom", fontsize=9)
    ax.set_xlabel("Team xG in match")
    ax.set_ylabel("Goal variance / mean")
    ax.set_ylim(0.4, 1.1)
    ax.set_title("Goals are under-dispersed (not fitted)", loc="left", color=ink, fontsize=11)
    ax.grid(axis="y", color=grid, linewidth=0.6)
    ax.legend(frameon=False, loc="lower left")

    ax = axes[2]
    top = list(sc_sim.index[:10])
    ys = range(len(top))
    ax.barh([i + 0.2 for i in ys], [100 * sc_ref.get(s, 0) for s in top], 0.38, color=c_ref, label="Reference model")
    ax.barh([i - 0.2 for i in ys], [100 * sc_sim[s] for s in top], 0.38, color=c_sim, label="Synthetic")
    ax.set_yticks(list(ys), top)
    ax.invert_yaxis()
    ax.set_xlabel("% of matches")
    ax.set_title("Most common scorelines (not fitted)", loc="left", color=ink, fontsize=11)
    ax.grid(axis="x", color=grid, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, loc="lower right")

    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seasons", type=int, default=20)
    ap.add_argument("--published", default="data")
    ap.add_argument("--out", default="VALIDATION.md")
    ap.add_argument("--chart", default="docs/validation.png")
    a = ap.parse_args()
    m, t, d = run(a.seasons, a.published, a.out, a.chart)
    print(json.dumps({k: round(v, 4) for k, v in m.items()}, indent=1))
    print(json.dumps({k: round(v, 3) for k, v in t.items()}, indent=1))
    for r in d:
        print(r)
